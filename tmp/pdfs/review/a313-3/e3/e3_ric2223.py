def write(nn, bom_txt, nets, notes):
    bom = [l.split('|') for l in bom_txt.strip().splitlines()]
    with open(OUT / f'ric{nn}_bom.csv', 'w', encoding='utf8', newline='') as f:
        w = csv.writer(f)
        w.writerow(['ref', 'name', 'qty', 'page', 'note'])
        for ref, name, page, note in bom:
            w.writerow([ref, name, 1, page, note])
    rows = []
    for net, pins in nets.items():
        for rp in pins.split():
            ref, pin = rp.split('.', 1)
            rows.append([ref, pin, net, notes.get(rp) or (notes.get(net) if rp == pins.split()[0] else '')
                         or notes.get(ref, '')])
    with open(OUT / f'ric{nn}_net.csv', 'w', encoding='utf8', newline='') as f:
        w = csv.writer(f)
        w.writerow(['ref', 'pin', 'net', 'note'])
        w.writerows(rows)
    # checks
    brefs = {b[0] for b in bom}
    nrefs = {r[0] for r in rows}
    dup = [k for k, v in Counter((r[0], r[1]) for r in rows).items() if v > 1]
    small = [n for n, p in nets.items() if n.startswith('N') and len(p.split()) < 2]
    assert len(brefs) == len(bom), 'trùng ref trong bom'
    print(f'рис.{nn}: bom {len(bom)} dòng, net {len(rows)} chân, {len(nets)} net')
    print('  bom∖net:', sorted(brefs - nrefs), ' net∖bom:', sorted(nrefs - brefs))
    print('  chân trùng:', dup, ' net nội bộ <2 chân:', small)
    assert not dup and not small and not (nrefs - brefs)


def par(*r):
    return 1 / sum(1 / x for x in r)


