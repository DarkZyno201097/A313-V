def members(spec):
    for tok in spec.split():
        m = re.fullmatch(r'П(\d+)/(\d+)([?+]*)', tok)
        assert m, tok
        yield int(m[1]), int(m[2]), m[3]


def norm(s):
    s = s.upper().replace('Ё', 'Е')
    s = re.sub(r'[\s.,"„“”«»¬\-_()·]', '', s)
    for a, b in [('АЦИ', 'АЦП'), ('ЦИ', 'ЦП'), ('ЦН', 'ЦП'), ('СЧК', 'СЧК'), ('РГ', 'РГ'), ('ОБЩИЙПРОВОД', 'ОБЩПРОВОДА'),
                 ('РАЗРЯД', 'Р'), ('КОМ', 'КОМ'), ('ВЫХ', 'ВЫХ')]:
        s = s.replace(a, b)
    s = re.sub(r'^(\d+)Р(.*)$', r'\2#\1', s)  # 7рСчК == СчК7р
    s = re.sub(r'(\d+)Р$', r'#\1', s)          # КША-7р == КША7
    s = re.sub(r'^(\D+)(\d+)$', r'\1#\2', s)
    return s


def same(a, b):
    na, nb = norm(a), norm(b)
    return na == nb or difflib.SequenceMatcher(None, na, nb).ratio() >= 0.8


def main():
    sig = {(r['table'], r['pin']): r['signal'] for r in csv.DictReader(open(E4 / 'e4_all.csv', encoding='utf8'))}
    tables = {r[0] for r in sig}
    mrows, nrows, seen_pin, empty, dup = [], [], {}, [], []
    for page, cols in PAGES.items():
        assert len(cols) == EXPECT[page], (page, len(cols))
        idx, fname = PHOTO[page]
        for i, (name, spec, note) in enumerate(cols, 1):
            cid = f'{page}-c{i:02d}'
            mem = list(members(spec))
            style = 'solid' if len(mem) > 1 else 'dashed'
            if not mem:
                empty.append(cid)
            for n, p, flag in mem:
                if (n, p) in seen_pin:
                    dup.append(f'П{n}/{p}: {seen_pin[(n, p)]} & {cid}')
                seen_pin[(n, p)] = cid
                nn = []
                if '?' in flag:
                    nn.append('đọc chưa chắc')
                if '+' in flag:
                    nn.append('nối vào cột bằng móc ⊓')
                mrows.append([page, f'#{idx} {fname}', cid, f'П{n}', p, style, '; '.join(nn)])
            nrows.append([cid, ';'.join(f'П{n}/{p}' for n, p, _ in mem), f'{name}' + (f' | {note}' if note else '')])
    with open(E4 / 'p153_157_matrix.csv', 'w', newline='', encoding='utf8') as f:
        w = csv.writer(f)
        w.writerow(['page', 'photo', 'column', 'connector', 'pin', 'line_style', 'note'])
        w.writerows(mrows)
    with open(E4 / 'matrix_nets.csv', 'w', newline='', encoding='utf8') as f:
        w = csv.writer(f)
        w.writerow(['net', 'members', 'note'])
        w.writerows(nrows)

    # kiểm chéo: tên tín hiệu của mọi chân trong bảng У16КПn phải giống nhau (và giống tên cột)
    ok = bad = single = 0
    report = []
    for page, cols in PAGES.items():
        for i, (name, spec, note) in enumerate(cols, 1):
            mem = list(members(spec))
            if not mem:
                continue
            names = []
            for n, p, _ in mem:
                t = f'У16КП{n}'
                names.append((f'П{n}/{p}', sig.get((t, str(p)), '<không có bảng>' if t not in tables else '')))
            known = [s for _, s in names if s and not s.startswith('<')]
            if len(mem) < 2:
                single += 1
            cons = all(same(known[0], s) for s in known[1:]) if known else False
            hdr = all(same(name, s) for s in known) if known else False
            if cons and len(known) == len(mem):
                ok += 1
                if not hdr:
                    report.append(('HEADER', f'{page}-c{i:02d}', name, names))
            else:
                bad += 1
                report.append(('MEMBERS', f'{page}-c{i:02d}', name, names))
    total = sum(len(c) for c in PAGES.values())
    print(f'{total} cột ({len(empty)} cột trống: {empty}), {len(mrows)} giao điểm; {single} cột 1 chấm')
    print('chân xuất hiện ở 2 cột:', dup)
    print(f'khớp tên giữa mọi chân: {ok}; không khớp/thiếu tên: {bad}')
    for kind, cid, name, names in report:
        print(kind, cid, name, '|', '; '.join(f'{a}={b!r}' for a, b in names))


