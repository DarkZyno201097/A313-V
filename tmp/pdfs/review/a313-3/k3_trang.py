def table():
    t = {}
    for a, b, p in RUNS:
        for i in range(a, b + 1):
            t[i] = (p + i - a, 'T', '')
    for i, v in ONE.items():
        assert i not in t, i
        t[i] = v
    return t


def main():
    t = table()
    assert sorted(t) == list(range(1, 250)), set(range(1, 250)) - set(t)
    files = [r for r in csv.DictReader(open(OUT / 'kiemke.csv', encoding='utf8'))]
    assert len(files) == 249
    # spot checks read by eye (goc_01, goc_06, tit1/tit2 crops)
    assert t[1][0] == 2 and t[22][0] == 23 and t[96][0] == 100 and t[105][0] == 109
    assert t[159][0] == 162 and t[234][0] == 232 and t[233][0] == 231
    pages = {}
    for i, (p, k, n) in t.items():
        if p is not None:
            pages.setdefault(p, []).append(i)
    rows = []
    for i in range(1, 250):
        p, k, n = t[i]
        r = files[i - 1]
        rows.append(dict(idx=i, file=r['file'], page='' if p is None else p, kind=k, note=n,
                         sharp=r['sharp'], same_page=' '.join('#%d' % j for j in pages.get(p, []) if j != i)))
    with open(OUT / 'trang.csv', 'w', newline='', encoding='utf8') as f:
        w = csv.DictWriter(f, list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    last = max(pages)
    missing = [p for p in range(2, last + 1) if p not in pages]
    print('pages seen:', len(pages), 'of 2..%d' % last)
    print('missing:', ' '.join(map(str, missing)))
    print('repeated:', '; '.join('%d: %s' % (p, ' '.join('#%d' % j for j in v)) for p, v in sorted(pages.items()) if len(v) > 1))
    print('no page number:', ' '.join('#%d(%s)' % (i, t[i][1]) for i in range(1, 250) if t[i][0] is None))


if __name__ == '__main__':
    main()
